async function applyOverrides() {
  for (const [langCode, affiliate] of Object.entries(AFFILIATE_OVERRIDES)) {
    const exportName = EXPORT_NAMES[langCode];
    const mod = await import(pathToFileURL(join(localesDir, `${langCode}.ts`)).href);
    const locale = mod[exportName];
    writeFileSync(
      join(localesDir, `${langCode}.ts`),
      `import type { LocaleTree } from './en';\n\nexport const ${exportName}: LocaleTree = ${JSON.stringify({ ...locale, affiliate }, null, 2)};\n`,
    );
    console.log(`${langCode}: manual affiliate override applied`);
  }
}

await applyOverrides();
