"""Write complete legal phrase maps for te, si, my, lo and fix ta."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHRASES = json.loads((ROOT / "scripts/legal-phrases.json").read_text(encoding="utf-8"))
OUT = ROOT / "src/content/legal/phraseMaps"

def write_map(code, values):
    assert len(values) == len(PHRASES) == 80, f"{code}: expected 80, got {len(values)}"
    data = dict(zip(PHRASES, values))
    path = OUT / f"{code}.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {path} ({len(data)} keys)")

