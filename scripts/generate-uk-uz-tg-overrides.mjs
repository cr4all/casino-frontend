function buildMap(translations, lang) {
  const map = {};
  const missing = [];
  const sameAsEnglish = [];
  const badPlaceholders = [];

  for (const phrase of phrases) {
    let value;
    if (unchanged.has(phrase)) {
      value = phrase;
    } else if (translations[phrase]) {
      value = translations[phrase];
    } else {
      missing.push(phrase);
      value = phrase;
    }
    map[phrase] = value;

    if (!unchanged.has(phrase) && value === phrase) {
      sameAsEnglish.push(phrase);
    }

    const enPh = [...phrase.matchAll(/\{\{[^}]+\}\}/g)].map((m) => m[0]).sort().join(',');
    const trPh = [...value.matchAll(/\{\{[^}]+\}\}/g)].map((m) => m[0]).sort().join(',');
    if (enPh !== trPh) badPlaceholders.push({ phrase, value, enPh, trPh });
  }

  if (missing.length) console.error(`[${lang}] missing ${missing.length}:`, missing.slice(0, 5));
  if (sameAsEnglish.length) console.error(`[${lang}] untranslated ${sameAsEnglish.length}:`, sameAsEnglish.slice(0, 5));
  if (badPlaceholders.length) console.error(`[${lang}] bad placeholders:`, badPlaceholders.slice(0, 3));

  return map;
}

function writeOverride(lang, map) {
  const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
  const out = join(outDir, `${lang}.json`);
  writeFileSync(out, `${JSON.stringify(sorted, null, 2)}\n`, 'utf8');
  const translated = Object.entries(map).filter(([k, v]) => k !== v).length;
  console.log(`${lang}: wrote ${Object.keys(map).length} keys, ${translated} translated -> ${out}`);
}

import { existsSync } from 'node:fs';

const uzPath = join(import.meta.dirname, 'override-data-uz.json');
const tgPath = join(import.meta.dirname, 'override-data-tg.json');

writeOverride('uk', buildMap(uk, 'uk'));

for (const [lang, dataPath] of [['uz', uzPath], ['tg', tgPath]]) {
  if (!existsSync(dataPath)) {
    console.error(`Missing ${dataPath}`);
    process.exitCode = 1;
    continue;
  }
  const data = JSON.parse(readFileSync(dataPath, 'utf8'));
  writeOverride(lang, buildMap(data, lang));
}
